// commands/utils/publicEnv.js
//
// One place for the build-time public environment. `slice build` writes both
// dist/slice-env.json (shared, auditable) and dist/slice-env.generated.js (the
// ESM shim the runtime imports). `slice export` copies them and `slice start`
// serves them as static files; no dynamic env endpoint is needed in production.
import fs from 'fs-extra';
import path from 'path';
import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';

let resolverPromise;

/**
 * Prefer the framework package export, but fall back to the package file path so
 * an older framework release still works.
 */
export async function loadPublicEnvResolver() {
  if (!resolverPromise) {
    resolverPromise = (async () => {
      try {
        return await import('slicejs-web-framework/api/framework/publicEnvResolver.js');
      } catch {
        const require = createRequire(import.meta.url);
        const entry = require.resolve('slicejs-web-framework');
        const packageRoot = path.resolve(path.dirname(entry), '..');
        return import(pathToFileURL(path.join(packageRoot, 'api', 'framework', 'publicEnvResolver.js')).href);
      }
    })();
  }
  return resolverPromise;
}

export async function resolvePublicEnvPayload(projectRoot) {
  const { resolvePublicEnv } = await loadPublicEnvResolver();
  return resolvePublicEnv({
    mode: 'production',
    envFilePath: path.join(projectRoot, '.env')
  });
}

/**
 * Writes both env artifacts into `<outDir>` and returns the number of public keys.
 * The JSON is the shared source of truth; the ESM shim exists because native JSON
 * modules are not available in every browser/webview Slice supports.
 */
export async function writeSliceEnv(outDir, projectRoot) {
  const payload = await resolvePublicEnvPayload(projectRoot);
  await writeSliceEnvPayload(outDir, payload);
  return Object.keys(payload.env || {}).length;
}

export function renderSliceEnvModule(payload) {
  return [
    '// Generated by slice build. Do not edit.',
    `const env = ${JSON.stringify(payload, null, 2)};`,
    'export default env;',
    ''
  ].join('\n');
}

export async function writeSliceEnvPayload(outDir, payload) {
  await fs.ensureDir(outDir);
  await fs.writeFile(
    path.join(outDir, 'slice-env.json'),
    `${JSON.stringify(payload, null, 2)}\n`,
    'utf8'
  );
  await fs.writeFile(
    path.join(outDir, 'slice-env.generated.js'),
    renderSliceEnvModule(payload),
    'utf8'
  );
}
