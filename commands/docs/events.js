import fs from 'fs-extra';
import path from 'path';

import {
   buildEventManifest,
   collectEventGraph,
   collectEventRegistry,
} from '../types/types.js';

const GENERATED_MARKER = '<!-- Generated by `slice docs generate events`. Do not edit by hand. -->';
// Mermaid reads `%%` comments; an HTML comment on the first line makes GitHub
// and the live editor reject the diagram ("No diagram type detected").
const GENERATED_MERMAID_MARKER = '%% Generated by `slice docs generate events`. Do not edit by hand.';

const escapeText = (value) => String(value ?? '').replace(/\r?\n/g, ' ').trim();
const escapeHtml = (value) =>
   escapeText(value)
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;');
const escapeMermaid = (value) => escapeText(value).replace(/"/g, '&quot;');

function namespaceOf(eventName) {
   const index = String(eventName).indexOf(':');
   return index > 0 ? String(eventName).slice(0, index) : null;
}

function slugify(value) {
   return String(value).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '') || 'events';
}

function fileForNamespace(namespace, used) {
   const base = namespace ? slugify(namespace) : 'invalid';
   let name = base;
   let counter = 2;
   while (used.has(name)) name = `${base}-${counter++}`;
   used.add(name);
   return `${name}.md`;
}

function rolesFor(event) {
   return [
      ...event.emitters.map((site) => ({ ...site, role: 'emitter' })),
      ...event.listeners.map((site) => ({ ...site, role: 'listener' })),
   ];
}

function uniqueComponents(event) {
   const set = new Set();
   for (const site of [...event.emitters, ...event.listeners]) {
      if (site.component) set.add(site.component);
   }
   return [...set].sort();
}

function renderPayload(payload) {
   if (payload == null) return '—';
   return `\`${JSON.stringify(payload)}\``;
}

function renderIndex(manifest, registry, namespaces, namespaceFiles) {
   const namespaceRows = Object.entries(namespaces).map(([namespace, events]) => {
      const emitters = new Set();
      const listeners = new Set();
      for (const event of events) {
         for (const site of event.emitters) if (site.component) emitters.add(site.component);
         for (const site of event.listeners) if (site.component) listeners.add(site.component);
      }
      return `| ${namespace} | ${events.length} | ${emitters.size} | ${listeners.size} | [${namespace}](./${namespaceFiles.get(namespace)}) | [diagram](./diagram-${namespaceFiles.get(namespace).replace(/\.md$/, '')}.mmd) |`;
   });

   const declaredNoEmitter = Object.entries(registry)
      .filter(([name]) => !manifest.events[name]?.emitters.length)
      .map(([name]) => `\`${name}\``);
   const usedUndeclared = Object.keys(manifest.events)
      .filter((name) => !(name in registry))
      .map((name) => `\`${name}\``);
   const invalidNames = Object.keys(manifest.events)
      .filter((name) => !namespaceOf(name))
      .map((name) => `\`${name}\``);
   const dynamicSites = [
      ...manifest.dynamic.emitters.map((site) => `emit ${site.file}:${site.line}`),
      ...manifest.dynamic.listeners.map((site) => `subscribe ${site.file}:${site.line}`),
   ];

   return `# Events

${GENERATED_MARKER}

This catalog is generated from \`slice.events.register(...)\` and the static
\`emit\`/\`subscribe\` call sites. The machine manifest is
[\`src/slice-events.generated.js\`](../../src/slice-events.generated.js).

## Summary

| Namespace | Events | Emitters | Listeners | Page | Diagram |
| --- | --- | --- | --- | --- | --- |
${namespaceRows.length ? namespaceRows.join('\n') : '| - | 0 | 0 | 0 | - | - |'}

## Diagram

- [Mermaid source, every event](./diagram.mmd)
- [Standalone HTML](./diagram.html)
- Each namespace has its own smaller diagram, linked in the table above. Blue nodes emit, green
  nodes listen, grey nodes do both; solid arrows are emits and dashed arrows are subscriptions.

## Drift

### Declared but never emitted

${declaredNoEmitter.length ? declaredNoEmitter.map((name) => `- ${name}`).join('\n') : '- None.'}

### Used but not declared

${usedUndeclared.length ? usedUndeclared.map((name) => `- ${name}`).join('\n') : '- None.'}

### Events without a namespace

${invalidNames.length ? invalidNames.map((name) => `- ${name}`).join('\n') : '- None.'}

### Dynamic sites (not statically resolvable)

${dynamicSites.length ? dynamicSites.map((site) => `- \`${site}\``).join('\n') : '- None.'}
`;
}

function renderNamespace(namespace, events) {
   const sections = events.map((event) => {
      const roles = rolesFor(event);
      const rows = roles.map((site) => {
         const component = site.component || path.basename(site.file, '.js');
         return `| ${site.role} | ${component} | ${site.category || '—'} | \`${site.file}:${site.line}\` |`;
      });
      return `## \`${event.name}\`

Payload: ${renderPayload(event.payload)}

| Role | Component | Category | Source |
| --- | --- | --- | --- |
${rows.length ? rows.join('\n') : '| — | — | — | — |'}
`;
   });

   return `# ${namespace} events

${GENERATED_MARKER}

${sections.length ? sections.join('\n') : 'No events in this namespace.'}
`;
}

const MERMAID_CLASS_DEFS = [
   '  classDef event fill:#ede9fe,stroke:#7c3aed,stroke-width:2px,color:#3b0764',
   '  classDef emitter fill:#dbeafe,stroke:#2563eb,color:#1e3a8a',
   '  classDef listener fill:#d1fae5,stroke:#059669,color:#064e3b',
   '  classDef both fill:#f1f5f9,stroke:#475569,color:#0f172a',
   '  classDef dynamic fill:#fef3c7,stroke:#d97706,color:#78350f,stroke-dasharray:4 3',
];

// Emitters on the left, events in the middle, listeners on the right. Mermaid
// lays a graph out from the edges, so these groups are what keeps the columns:
// a component that only emits can never be ranked after an event.
function renderFlow(manifest, events, groups, direction = 'TD') {
   const nameOf = (site) => site.component || path.basename(site.file, '.js');
   const emitters = new Set();
   const listeners = new Set();
   for (const event of events) {
      for (const site of event.emitters) emitters.add(nameOf(site));
      for (const site of event.listeners) listeners.add(nameOf(site));
   }

   const lines = [`flowchart ${direction}`];
   const eventIds = new Map();
   const componentIds = new Map();
   let counter = 0;
   const idForComponent = (name) => {
      if (!componentIds.has(name)) componentIds.set(name, `c${counter++}`);
      return componentIds.get(name);
   };
   const unique = (values) => [...new Set(values)];

   if (groups) {
      for (const [namespace, namespaceEvents] of Object.entries(groups)) {
         lines.push(`  subgraph ns${counter++}["${escapeMermaid(namespace)}"]`);
         for (const event of namespaceEvents) {
            const eventId = `e${counter++}`;
            // The id lives in a map, not on the event object: `namespaces`
            // holds copies, so writing `event._diagramId` left every edge
            // without a target and the diagram rendered as a list of boxes.
            eventIds.set(event.name, eventId);
            lines.push(`    ${eventId}(["${escapeMermaid(event.name)}"]):::event`);
         }
         lines.push('  end');
      }
   } else {
      lines.push('  subgraph events["Events"]');
      for (const event of events) {
         const eventId = `e${counter++}`;
         eventIds.set(event.name, eventId);
         lines.push(`    ${eventId}(["${escapeMermaid(event.name)}"]):::event`);
      }
      lines.push('  end');
   }

   const eventOrder = new Map(Object.keys(manifest.events).map((name, index) => [name, index]));
   const firstEventOf = (name) => {
      let first = Number.MAX_SAFE_INTEGER;
      for (const [eventName, event] of Object.entries(manifest.events)) {
         if (event.emitters.some((site) => nameOf(site) === name)) {
            first = Math.min(first, eventOrder.get(eventName));
         }
      }
      return first;
   };
   const roleGroups = { emitter: [], listener: [], both: [] };
   for (const name of [...new Set([...emitters, ...listeners])]) {
      const role = emitters.has(name) && listeners.has(name) ? 'both' : emitters.has(name) ? 'emitter' : 'listener';
      roleGroups[role].push(name);
   }
   for (const group of Object.values(roleGroups)) {
      group.sort((a, b) => firstEventOf(a) - firstEventOf(b) || a.localeCompare(b));
   }
   for (const [role, label] of [['emitter', 'Emitters'], ['listener', 'Listeners']]) {
      if (!roleGroups[role].length) continue;
      lines.push(`  subgraph ${role}Group["${label}"]`);
      for (const name of roleGroups[role]) {
         lines.push(`    ${idForComponent(name)}["${escapeMermaid(name)}"]:::${role}`);
      }
      lines.push('  end');
   }
   for (const name of roleGroups.both) {
      lines.push(`  ${idForComponent(name)}["${escapeMermaid(name)}"]:::both`);
   }

   for (const event of events) {
      const eventId = eventIds.get(event.name);
      if (!eventId) continue;
      for (const emitter of unique(event.emitters.map(nameOf))) {
         lines.push(`  ${idForComponent(emitter)} --> ${eventId}`);
      }
      for (const listener of unique(event.listeners.map(nameOf))) {
         lines.push(`  ${eventId} -.-> ${idForComponent(listener)}`);
      }
   }

   if (!groups) {
      lines.push(...MERMAID_CLASS_DEFS);
      return `${lines.join('\n')}\n`;
   }

   if (manifest.dynamic.emitters.length || manifest.dynamic.listeners.length) {
      lines.push('  dynamic(["dynamic sites"]):::dynamic');
      for (const site of manifest.dynamic.emitters) {
         lines.push(`  ${idForComponent(nameOf(site))} -.-> dynamic`);
      }
      for (const site of manifest.dynamic.listeners) {
         lines.push(`  dynamic -.-> ${idForComponent(nameOf(site))}`);
      }
   }

   lines.push(...MERMAID_CLASS_DEFS);
   return `${lines.join('\n')}\n`;
}

function renderMermaid(manifest, namespaces) {
   // Top to bottom keeps the sheet horizontal: emitters in a row, then the
   // events, then the listeners.
   return renderFlow(manifest, Object.values(namespaces).flat(), namespaces, 'TD');
}

function renderNamespaceMermaid(manifest, events) {
   // A family is one event and its fan: top to bottom is a wide, short sheet.
   return renderFlow(manifest, events, null, 'TD');
}

function renderHtml(manifest, namespaces, registry) {
   const sections = Object.entries(namespaces).map(([namespace, events]) => {
      const NODE_H = 24;
      const NODE_GAP = 6;
      const EVENT_H = 32;
      const ROW_GAP = 28;
      const HEADER_H = 26;
      let cursorY = HEADER_H + 8;
      const eventNodes = events.map((event) => {
         const emitters = [...new Set(event.emitters.map((site) => site.component || path.basename(site.file, '.js')))];
         const listeners = [...new Set(event.listeners.map((site) => site.component || path.basename(site.file, '.js')))];
         // One event can have many emitters (a toast shown from everywhere) and
         // the old fixed 80px row put them outside the viewBox. The row grows
         // with the taller of the two stacks instead, and every box is centred.
         const slots = Math.max(emitters.length, listeners.length, 1);
         const stackHeight = slots * NODE_H + (slots - 1) * NODE_GAP;
         const rowHeight = Math.max(stackHeight, EVENT_H);
         const top = cursorY;
         const rowY = top + (rowHeight - EVENT_H) / 2;
         const stackTop = top + (rowHeight - stackHeight) / 2;
         const emitterNodes = emitters.map((name, i) => ({
            name,
            y: stackTop + i * (NODE_H + NODE_GAP),
            x: 20,
            w: 180
         }));
         const listenerNodes = listeners.map((name, i) => ({
            name,
            y: stackTop + i * (NODE_H + NODE_GAP),
            x: 900,
            w: 180
         }));
         cursorY += rowHeight + ROW_GAP;
         const eventX = 440;
         const eventW = 220;
         const lines = [
            ...emitterNodes.map((node) => `<line x1="${node.x + node.w}" y1="${node.y + NODE_H / 2}" x2="${eventX}" y2="${rowY + EVENT_H / 2}" />`),
            ...listenerNodes.map((node) => `<line x1="${eventX + eventW}" y1="${rowY + EVENT_H / 2}" x2="${node.x}" y2="${node.y + NODE_H / 2}" />`),
         ];
         const boxes = [
            ...emitterNodes.map((node) => `<g class="emitter"><rect x="${node.x}" y="${node.y}" width="${node.w}" height="${NODE_H}" rx="6" /><text x="${node.x + 8}" y="${node.y + 16}">${escapeHtml(node.name)}</text></g>`),
            ...listenerNodes.map((node) => `<g class="listener"><rect x="${node.x}" y="${node.y}" width="${node.w}" height="${NODE_H}" rx="6" /><text x="${node.x + 8}" y="${node.y + 16}">${escapeHtml(node.name)}</text></g>`),
            `<g class="event"><rect x="${eventX}" y="${rowY}" width="${eventW}" height="${EVENT_H}" rx="16" /><text x="${eventX + 12}" y="${rowY + 21}">${escapeHtml(event.name)}</text></g>`,
         ];
         return { lines: lines.join(''), boxes: boxes.join('') };
      });
      // The last row already paid its gap; keep a matching margin at the bottom.
      const height = Math.max(120, cursorY - ROW_GAP + 24);
      const header = `<text class="col" x="20" y="${HEADER_H - 6}">Emitters</text>
<text class="col" x="440" y="${HEADER_H - 6}">Event</text>
<text class="col" x="900" y="${HEADER_H - 6}">Listeners</text>`;
      return `<section id="ns-${slugify(namespace)}">
<h2>${escapeHtml(namespace)}</h2>
<svg viewBox="0 0 1100 ${height}" role="img" aria-label="${escapeHtml(namespace)} event graph: emitters on the left, listeners on the right">
${header}
${eventNodes.map((node) => node.lines).join('')}
${eventNodes.map((node) => node.boxes).join('')}
</svg>
</section>`;
   });

   const rows = Object.entries(namespaces).map(([namespace, events]) =>
      `<tr><td>${escapeHtml(namespace)}</td><td>${events.length}</td><td><a href="#ns-${slugify(namespace)}">graph</a></td></tr>`,
   );

   return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Slice events</title>
<style>
:root { color-scheme: light dark; font-family: ui-sans-serif, system-ui, sans-serif; }
body { margin: 0 auto; max-width: 1180px; padding: 32px; line-height: 1.5; }
table { border-collapse: collapse; width: 100%; margin: 16px 0 32px; }
th, td { border-bottom: 1px solid color-mix(in srgb, currentColor 20%, transparent); padding: 8px; text-align: left; }
section { margin-top: 36px; }
svg { width: 100%; height: auto; border: 1px solid color-mix(in srgb, currentColor 16%, transparent); border-radius: 12px; }
rect { fill: color-mix(in srgb, currentColor 8%, transparent); stroke: color-mix(in srgb, currentColor 24%, transparent); }
text { fill: currentColor; font-size: 12px; }
line { stroke: color-mix(in srgb, currentColor 35%, transparent); stroke-width: 1.5; }
.event rect { fill: color-mix(in srgb, #7c3aed 18%, transparent); }
.emitter rect { fill: color-mix(in srgb, #2563eb 12%, transparent); stroke: color-mix(in srgb, #2563eb 32%, transparent); }
.listener rect { fill: color-mix(in srgb, #059669 12%, transparent); stroke: color-mix(in srgb, #059669 32%, transparent); }
.col { font-size: 11px; font-weight: 600; letter-spacing: 0.06em; text-transform: uppercase; fill: color-mix(in srgb, currentColor 55%, transparent); }
code { font-family: ui-monospace, SFMono-Regular, monospace; }
</style>
</head>
<body>
${GENERATED_MARKER}
<h1>Slice events</h1>
<p>Generated from <code>slice.events.register(...)</code> and static emit/subscribe sites. The machine manifest is <a href="../../src/slice-events.generated.js"><code>src/slice-events.generated.js</code></a>.</p>
<table><thead><tr><th>Namespace</th><th>Events</th><th>Graph</th></tr></thead><tbody>
${rows.join('\n') || '<tr><td>—</td><td>0</td><td>—</td></tr>'}
</tbody></table>
<p>Declared events: ${Object.keys(registry).length}. Total events: ${Object.keys(manifest.events).length}.</p>
${sections.join('\n') || '<p>No events registered.</p>'}
</body>
</html>
`;
}

export async function buildEventDocs({ projectRoot }) {
   const registry = await collectEventRegistry({ projectRoot });
   const graph = await collectEventGraph({ projectRoot });
   const manifest = buildEventManifest(registry, graph);
   const namespaces = {};
   for (const name of Object.keys(manifest.events).sort((a, b) => a.localeCompare(b))) {
      const namespace = namespaceOf(name) || 'invalid';
      if (!namespaces[namespace]) namespaces[namespace] = [];
      namespaces[namespace].push({ name, ...manifest.events[name] });
   }
   for (const events of Object.values(namespaces)) {
      events.sort((a, b) => a.name.localeCompare(b.name));
   }

   const outDir = path.join(projectRoot, 'docs', 'events');
   const files = new Map();
   const usedNames = new Set();
   const namespaceFiles = new Map();
   for (const [namespace, events] of Object.entries(namespaces)) {
      const file = fileForNamespace(namespace, usedNames);
      namespaceFiles.set(namespace, file);
      files.set(path.join(outDir, file), renderNamespace(namespace, events));
      // One small diagram per event family: the whole graph is a map, this is
      // the one a reader can actually follow.
      const diagramFile = `diagram-${file.replace(/\.md$/, '')}.mmd`;
      files.set(path.join(outDir, diagramFile), `${GENERATED_MERMAID_MARKER}\n\n${renderNamespaceMermaid(manifest, events)}`);
   }
   files.set(path.join(outDir, 'index.md'), renderIndex(manifest, registry, namespaces, namespaceFiles));
   files.set(path.join(outDir, 'diagram.mmd'), `${GENERATED_MERMAID_MARKER}\n\n${renderMermaid(manifest, namespaces)}`);
   files.set(path.join(outDir, 'diagram.html'), renderHtml(manifest, namespaces, registry));
   return { files, manifest, registry, namespaces };
}

export async function generateEventDocs({ projectRoot }) {
   const { files } = await buildEventDocs({ projectRoot });
   const outDir = path.join(projectRoot, 'docs', 'events');
   await fs.ensureDir(outDir);

   // Remove only generated pages that are no longer in the current graph.
   if (await fs.pathExists(outDir)) {
      for (const entry of await fs.readdir(outDir)) {
         const fullPath = path.join(outDir, entry);
         if (!(await fs.stat(fullPath)).isFile() || files.has(fullPath)) continue;
         const head = (await fs.readFile(fullPath, 'utf8')).slice(0, 300);
         if (head.includes('Generated by `slice docs generate events`')) await fs.remove(fullPath);
      }
   }

   for (const [filePath, content] of files) {
      await fs.ensureDir(path.dirname(filePath));
      await fs.writeFile(filePath, content, 'utf8');
   }
   return { files: [...files.keys()] };
}

export async function checkEventDocs({ projectRoot }) {
   const { files } = await buildEventDocs({ projectRoot });
   const issues = [];
   const expected = new Set(files.keys());
   for (const [filePath, content] of files) {
      if (!(await fs.pathExists(filePath))) {
         issues.push(`missing ${path.relative(projectRoot, filePath).replace(/\\/g, '/')}`);
         continue;
      }
      const actual = await fs.readFile(filePath, 'utf8');
      if (actual !== content) issues.push(`outdated ${path.relative(projectRoot, filePath).replace(/\\/g, '/')}`);
   }

   const outDir = path.join(projectRoot, 'docs', 'events');
   if (await fs.pathExists(outDir)) {
      for (const entry of await fs.readdir(outDir)) {
         const fullPath = path.join(outDir, entry);
         if (expected.has(fullPath) || !(await fs.stat(fullPath)).isFile()) continue;
         const head = (await fs.readFile(fullPath, 'utf8')).slice(0, 300);
         if (head.includes('Generated by `slice docs generate events`')) {
            issues.push(`orphan ${path.relative(projectRoot, fullPath).replace(/\\/g, '/')}`);
         }
      }
   }

   return { ok: issues.length === 0, issues };
}
